const DICTS: Record<Lang, Dict> = { en, zh };
export const dict = (lang: Lang) => DICTS[lang];

export function timeAgo(d: Date | string, lang: Lang, now = Date.now()): string {
  const t = dict(lang);
  const min = Math.floor((now - new Date(d).getTime()) / 60_000);
  if (min < 60) return t.ago(Math.max(0, min), "m").trim();
  if (min < 48 * 60) return t.ago(Math.floor(min / 60), "h").trim();
  return t.ago(Math.floor(min / 1440), "d").trim();
}
